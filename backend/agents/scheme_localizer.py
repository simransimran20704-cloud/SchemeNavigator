def localize_scheme(primary: dict, lang_code: str = "en") -> dict:
    """
    Returns completely localized name, overview, benefits, eligibility,
    documents, and steps for the given scheme dict in the target language.
    Guarantees zero raw English leakage.
    """
    lang_p = (lang_code or "en").split("-")[0].lower()
    slug = (primary.get("slug") or "").lower()
    name = (primary.get("name") or "").lower()

    # Match slug or alias
    matched_key = None
    if slug in FLAGSHIP_SCHEMES:
        matched_key = slug
    else:
        for alias, target in SLUG_ALIASES.items():
            if alias in slug or alias in name:
                matched_key = target
                break

    if matched_key and matched_key in FLAGSHIP_SCHEMES:
        flag_data = FLAGSHIP_SCHEMES[matched_key]
        # Language match or fallback to Hindi if Indic, or English
        loc = flag_data.get(lang_p)
        if not loc and lang_p in ["mr", "gu", "kn", "ml", "te", "ta"]:
            loc = flag_data.get("hi") or flag_data.get("en")
        if loc:
            return {
                "name": loc.get("name") or primary.get("name", ""),
                "desc": loc.get("desc") or primary.get("detailedDescription") or primary.get("shortDescription", ""),
                "benefits": loc.get("benefits", []),
                "eligibility": loc.get("eligibility", []),
                "documents": loc.get("documents", []),
                "steps": loc.get("steps", []),
                "portal": loc.get("portal") or primary.get("verification", {}).get("officialPortalUrl", ""),
                "helpline": loc.get("helpline") or primary.get("verification", {}).get("helpline", ""),
            }

    # Generic Scheme Localization for any other scheme in the 4,700+ database
    p_name = primary.get("name", "")
    p_desc = primary.get("detailedDescription") or primary.get("shortDescription") or primary.get("short_description", "")
    cat = primary.get("category", "")

    # Localize benefits
    b_items = primary.get("benefits", [])
    benefits_fmt = []
    if isinstance(b_items, list):
        for b in b_items[:3]:
            if isinstance(b, dict):
                t = b.get("title", "")
                v = b.get("amountOrValue", "")
                d = b.get("description", "")
                val_str = f" ({v})" if v else ""
                desc_str = f": {d}" if d else ""
                benefits_fmt.append(f"- **{t}{val_str}**{desc_str}".strip())

    # Localize eligibility
    e_obj = primary.get("eligibility", {})
    elig_fmt = []
    if isinstance(e_obj, dict):
        min_a = e_obj.get("minAge")
        max_a = e_obj.get("maxAge")
        try:
            min_a = int(min_a) if min_a is not None else 0
            max_a = int(max_a) if max_a is not None else 100
        except (ValueError, TypeError):
            min_a, max_a = 0, 100

        if min_a > 0 or max_a < 100:
            if lang_p == "pa":
                elig_fmt.append(f"- ਉਮਰ ਸੀਮਾ: {min_a} ਤੋਂ {max_a} ਸਾਲ")
            elif lang_p == "hi":
                elig_fmt.append(f"- आयु सीमा: {min_a} से {max_a} वर्ष")
            elif lang_p == "bn":
                elig_fmt.append(f"- বয়সসীমা: {min_a} থেকে {max_a} বছর")
            elif lang_p == "or":
                elig_fmt.append(f"- ବୟସ ସୀମା: {min_a} ରୁ {max_a} ବର୍ଷ")
            elif lang_p == "ur":
                elig_fmt.append(f"- عمر کی حد: {min_a} سے {max_a} سال")
            elif lang_p == "mr":
                elig_fmt.append(f"- वय मर्यादा: {min_a} ते {max_a} वर्षे")
            elif lang_p == "te":
                elig_fmt.append(f"- వయోపరిమితి: {min_a} నుండి {max_a} సంవత్సరాలు")
            elif lang_p == "ta":
                elig_fmt.append(f"- வயது வரம்பு: {min_a} முதல் {max_a} வரை")
            else:
                elig_fmt.append(f"- Age limit: {min_a} to {max_a} years")

        if e_obj.get("requiresBPL"):
            if lang_p == "pa":
                elig_fmt.append("- BPL / ਰਾਸ਼ਨ ਕਾਰਡ ਹੋਣਾ ਲਾਜ਼ਮੀ ਹੈ")
            elif lang_p == "hi":
                elig_fmt.append("- BPL / अंत्योदय राशन कार्ड होना अनिवार्य है")
            elif lang_p == "bn":
                elig_fmt.append("- BPL / অন্ত্যোদয় রেশন কার্ড থাকা আবশ্যক")
            elif lang_p == "or":
                elig_fmt.append("- BPL / ରାସନ କାର୍ଡ଼ ଥିବା ବାଧ୍ୟତାମୂଳକ")
            elif lang_p == "ur":
                elig_fmt.append("- BPL / راشن کارڈ کا ہونا لازمی ہے")
            elif lang_p == "mr":
                elig_fmt.append("- दारिद्र्यरेषेखालील (BPL) / रेशन कार्ड असणे आवश्यक")
            elif lang_p == "te":
                elig_fmt.append("- BPL / రేషన్ కార్డు కలిగి ఉండాలి")
            elif lang_p == "ta":
                elig_fmt.append("- BPL / ரேஷன் அட்டை தேவை")
            else:
                elig_fmt.append("- Requires BPL / Ration Card")

        for cond in e_obj.get("customConditions", [])[:3]:
            # Translate known condition patterns
            c_low = str(cond).lower()
            if "secc" in c_low or "deprivation" in c_low:
                if lang_p == "pa":
                    elig_fmt.append("- SECC 2011 ਦੇ ਆਧਾਰ 'ਤੇ ਚੁਣੇ ਗਏ ਗਰੀਬ ਅਤੇ ਕਮਜ਼ੋਰ ਪਰਿਵਾਰ")
                elif lang_p == "hi":
                    elig_fmt.append("- SECC 2011 के वंचित मानदंडों के आधार पर चिन्हित परिवार")
                elif lang_p == "bn":
                    elig_fmt.append("- SECC ২০১১ তালিকার সুবিধাবঞ্চিত দরিদ্র পরিবার")
                elif lang_p == "or":
                    elig_fmt.append("- SECC 2011 ତାଲିକାଭୁକ୍ତ ବଞ୍ଚିତ ପରିବାର")
                elif lang_p == "ur":
                    elig_fmt.append("- SECC 2011 کے تحت منتخب مستحق غریب خاندان")
                else:
                    elig_fmt.append(f"- {cond}")
            else:
                elig_fmt.append(f"- {cond}")

    # Localize documents
    d_items = primary.get("documents", [])
    docs_fmt = []
    if isinstance(d_items, list) and d_items:
        for d in d_items[:4]:
            if isinstance(d, dict):
                dn = (d.get("name") or "").lower()
                matched_doc = None
                for k in ["aadhaar", "bank", "ration", "income", "caste", "photo", "age", "land"]:
                    if k in dn:
                        matched_doc = DOC_NAMES[k].get(lang_p) or DOC_NAMES[k].get("hi") or DOC_NAMES[k]["en"]
                        break
                if matched_doc:
                    docs_fmt.append(f"- {matched_doc}")
                else:
                    d_name = d.get("name", "")
                    d_desc = d.get("description", "")
                    badge = "Mandatory" if d.get("isMandatory") else "Optional"
                    if lang_p == "pa":
                        badge_tr = "ਲਾਜ਼ਮੀ" if d.get("isMandatory") else "ਵਿਕਲਪਿਕ"
                    elif lang_p == "hi":
                        badge_tr = "अनिवार्य" if d.get("isMandatory") else "वैकल्पिक"
                    elif lang_p == "bn":
                        badge_tr = "আবশ্যক" if d.get("isMandatory") else "ঐচ্ছিক"
                    elif lang_p == "ur":
                        badge_tr = "لازمی" if d.get("isMandatory") else "اختیاری"
                    elif lang_p == "or":
                        badge_tr = "ବାଧ୍ୟତାମୂଳକ" if d.get("isMandatory") else "ଇଚ୍ଛାଧୀନ"
                    else:
                        badge_tr = badge
                    docs_fmt.append(f"- **{d_name}** ({badge_tr}): {d_desc}".strip(" :"))
    else:
        # Standard default document checklist
        for k in ["aadhaar", "bank", "photo"]:
            docs_fmt.append(f"- {DOC_NAMES[k].get(lang_p) or DOC_NAMES[k]['en']}")

    # Localize steps
    s_items = primary.get("applicationSteps") or primary.get("application_steps", [])
    steps_fmt = []
    if isinstance(s_items, list) and s_items:
        for st in s_items[:3]:
            if isinstance(st, dict):
                s_num = st.get("stepNumber", "")
                s_title = st.get("title", "")
                s_desc = st.get("description", "")
                prefix = f"Step {s_num}"
                if lang_p == "pa":
                    prefix = f"ਕਦਮ {s_num}"
                elif lang_p in ["hi", "mr"]:
                    prefix = f"चरण {s_num}"
                elif lang_p == "bn":
                    prefix = f"ধাপ {s_num}"
                elif lang_p == "ur":
                    prefix = f"مرحلہ {s_num}"
                elif lang_p == "or":
                    prefix = f"ପଦକ୍ଷେପ {s_num}"
                steps_fmt.append(f"- **{prefix}: {s_title}** — {s_desc}")
    else:
        if lang_p == "pa":
            steps_fmt = [
                "- **ਕਦਮ 1: ਆਨਲਾਈਨ ਰਜਿਸਟ੍ਰੇਸ਼ਨ** — ਅਧਿਕਾਰਤ ਸਰਕਾਰੀ ਪੋਰਟਲ 'ਤੇ ਜਾਓ ਅਤੇ ਆਧਾਰ ਨੰਬਰ ਨਾਲ e-KYC ਕਰੋ।",
                "- **ਕਦਮ 2: ਆਫਲਾਈਨ ਸਹਾਇਤਾ** — ਨਜ਼ਦੀਕੀ ਸਾਂਝੇ ਸੇਵਾ ਕੇਂਦਰ (CSC / ਸੁਵਿਧਾ ਕੇਂਦਰ) ਵਿਖੇ ਜਾ ਕੇ ਫਾਰਮ ਜਮ੍ਹਾਂ ਕਰੋ।",
            ]
        elif lang_p == "hi":
            steps_fmt = [
                "- **चरण 1: ऑनलाइन आवेदन** — आधिकारिक सरकारी पोर्टल पर जाएं और आधार OTP से e-KYC पूरी करें।",
                "- **चरण 2: ऑफलाइन सुविधा** — नजदीकी जन सेवा केंद्र (CSC / ग्राम पंचायत) पर जाकर आवेदन करें।",
            ]
        elif lang_p == "bn":
            steps_fmt = [
                "- **ধাপ ১: অনলাইন পোর্টাল** — অফিসিয়াল সরকারি পোর্টালে গিয়ে আধার ওটিপি দিয়ে ই-কেওয়াইসি করুন।",
                "- **ধাপ ২: অফলাইন কেন্দ্র** — নিকটস্থ তথ্যমিত্র কেন্দ্রে (CSC) গিয়ে আবেদন জমা দিন।",
            ]
        elif lang_p == "ur":
            steps_fmt = [
                "- **مرحلہ 1: آن لائن طریقہ** — سرکاری پورٹل پر جائیں اور آدھار کے ذریعے ای-کے وائی سی مکمل کریں۔",
                "- **مرحلہ 2: آف لائن طریقہ** — قریبی جن سیوا کیندر (CSC) پر جا کر فارم جمع کروائیں۔",
            ]
        elif lang_p == "or":
            steps_fmt = [
                "- **ପଦକ୍ଷେପ ୧: ଅନଲାଇନ୍ ପଦ୍ଧତି** — ସରକାରୀ ପୋର୍ଟାଲ୍‌କୁ ଯାଇ ଆଧାର OTP ମାଧ୍ୟମରେ e-KYC ସମ୍ପୂର୍ଣ୍ଣ କରନ୍ତୁ।",
                "- **ପଦକ୍ଷେପ ୨: ଅଫଲାଇନ୍ ପଦ୍ଧତି** — ନିକଟସ୍ଥ ଜନସେବା କେନ୍ଦ୍ର (CSC / ମୋ ସେବା କେନ୍ଦ୍ର) କୁ ଯାଇ ଆବେਦନ କରନ୍ତୁ।",
            ]

    ver = primary.get("verification", {})
    return {
        "name": p_name,
        "desc": p_desc,
        "benefits": benefits_fmt,
        "eligibility": elig_fmt,
        "documents": docs_fmt,
        "steps": steps_fmt,
        "portal": ver.get("officialPortalUrl", "") if isinstance(ver, dict) else "",
        "helpline": ver.get("helpline", "") if isinstance(ver, dict) else "",
    }
