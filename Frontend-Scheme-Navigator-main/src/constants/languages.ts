export const getLanguageByCode = (code: string): LanguageInfo => {
  if (!code) return TOP_INDIAN_LANGUAGES[0];
  const normalized = code.toLowerCase().trim();
  return (
    TOP_INDIAN_LANGUAGES.find(
      (l) =>
        l.code.toLowerCase() === normalized ||
        l.speechCode.toLowerCase() === normalized ||
        l.name.toLowerCase() === normalized ||
        l.nativeName.toLowerCase() === normalized
    ) || TOP_INDIAN_LANGUAGES[0]
  );
};
