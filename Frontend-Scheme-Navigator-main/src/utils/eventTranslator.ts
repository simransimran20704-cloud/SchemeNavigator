/**
 * Translates an arbitrary phrase using the dictionary, glossary, and Gemini cache.
 */
export function translateEventPhrase(phrase: string, langCode: string): string {
  if (!phrase || !langCode || langCode === 'en-IN' || langCode === 'en') return phrase;

  const trimmed = phrase.trim();
  if (!trimmed) return phrase;

  // 1. Direct event glossary check
  if (EVENT_TERM_GLOSSARY[trimmed]?.[langCode]) {
    return EVENT_TERM_GLOSSARY[trimmed][langCode];
  }

  // 2. Case-insensitive dictionary check
  const lower = trimmed.toLowerCase();
  for (const [key, map] of Object.entries(EVENT_TERM_GLOSSARY)) {
    if (key.toLowerCase() === lower && map[langCode]) {
      return map[langCode];
    }
  }

  // 3. Fallback to global SchemeNavigator glossary
  const glossaryResult = translateGlossaryPhrase(trimmed, langCode);
  if (glossaryResult && glossaryResult !== trimmed) {
    return glossaryResult;
  }

  // 4. Gemini AI cached translation
  const geminiCached = getCachedTranslation(trimmed, langCode);
  if (geminiCached) {
    return geminiCached;
  }

  // 5. Trigger background Gemini translation if English text has substance
  if (typeof window !== 'undefined' && /[a-zA-Z]{3,}/.test(trimmed)) {
    translateWithGemini(trimmed, langCode).catch(() => {});
  }

  return trimmed;
}

/**
 * Translates a Government Event into the target language.
 */
export function translateGovtEvent(event: GovtEvent, langCode: string): GovtEvent {
  if (!event || !langCode || langCode === 'en-IN' || langCode === 'en') return event;

  return {
    ...event,
    title: translateEventPhrase(event.title, langCode),
    category: translateEventPhrase(event.category, langCode),
    organizer: translateEventPhrase(event.organizer, langCode),
    description: translateEventPhrase(event.description, langCode),
    mode: event.mode,
    venue: event.venue ? translateEventPhrase(event.venue, langCode) : event.venue,
    price: event.price ? translateEventPhrase(event.price, langCode) : event.price,
    eligibility: event.eligibility ? translateEventPhrase(event.eligibility, langCode) : event.eligibility,
    rewards: event.rewards ? translateEventPhrase(event.rewards, langCode) : event.rewards,
    state: event.state ? translateEventPhrase(event.state, langCode) : event.state,
  };
}

/**
 * Translates a Brabble.ai Live Event into the target language.
 */
export function translateParseEvent(event: ParseBotEvent, langCode: string): ParseBotEvent {
  if (!event || !langCode || langCode === 'en-IN' || langCode === 'en') return event;

  const translatedEligibility = Array.isArray(event.eligibility)
    ? event.eligibility.map((el) => translateEventPhrase(el, langCode))
    : event.eligibility;

  return {
    ...event,
    title: translateEventPhrase(event.title, langCode),
    category: translateEventPhrase(event.category, langCode),
    genre: event.genre ? translateEventPhrase(event.genre, langCode) : event.genre,
    organiser: event.organiser ? translateEventPhrase(event.organiser, langCode) : event.organiser,
    mode: event.mode,
    price: event.price ? translateEventPhrase(event.price, langCode) : event.price,
    venue: event.venue ? translateEventPhrase(event.venue, langCode) : event.venue,
    city: event.city ? translateEventPhrase(event.city, langCode) : event.city,
    eligibility: translatedEligibility,
    platform: event.platform ? translateEventPhrase(event.platform, langCode) : event.platform,
  };
}

/**
 * Translates a Welfare Event Camp into the target language.
 */
export function translateWelfareEvent(event: WelfareEvent, langCode: string): WelfareEvent {
  if (!event || !langCode || langCode === 'en-IN' || langCode === 'en') return event;

  const translatedKeyBenefits = Array.isArray(event.keyBenefits)
    ? event.keyBenefits.map((b) => translateEventPhrase(b, langCode))
    : event.keyBenefits;

  const translatedRequiredDocuments = Array.isArray(event.requiredDocuments)
    ? event.requiredDocuments.map((d) => translateEventPhrase(d, langCode))
    : event.requiredDocuments;

  return {
    ...event,
    title: langCode === 'hi-IN' && event.hindiTitle ? event.hindiTitle : translateEventPhrase(event.title, langCode),
    hindiTitle: event.hindiTitle ? translateEventPhrase(event.hindiTitle, langCode) : undefined,
    category: event.category,
    organizer: translateEventPhrase(event.organizer, langCode),
    venue: translateEventPhrase(event.venue, langCode),
    district: translateEventPhrase(event.district, langCode),
    state: translateEventPhrase(event.state, langCode),
    description: translateEventPhrase(event.description, langCode),
    badge: translateEventPhrase(event.badge, langCode),
    keyBenefits: translatedKeyBenefits,
    requiredDocuments: translatedRequiredDocuments,
  };
}
