/**
 * Normalizes ministry and authority names by stripping redundant suffixes and uniform casing.
 */
export const normalizeMinistryKey = (raw: string): string => {
  if (!raw) return '';
  if (typeof raw !== 'string') raw = String(raw || '');
  return raw
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/,\s*Govt(?:\.|\s+of\s+India)?/gi, '')
    .replace(/,\s*Government\s+of\s+India/gi, '')
    .replace(/\(Govt\.?\s*of\s*India\)/gi, '')
    .replace(/\bGovt\.?\s*of\s*India\b/gi, '')
    .replace(/\bOf\b/g, 'of')
    .replace(/\bAnd\b/g, 'and')
    .trim();
};

