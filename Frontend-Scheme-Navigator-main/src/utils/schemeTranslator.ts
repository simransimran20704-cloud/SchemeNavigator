/**
 * Translates application steps dynamically
 */
export const translateApplicationStep = (step: ApplicationStep, langCode: string = 'en-IN'): ApplicationStep => {
  if (!step || langCode === 'en-IN' || langCode === 'en') return step;

  try {
    const titleLower = String(step.title || '').toLowerCase();
    let key = '';

    if (titleLower.includes('check eligibility') || titleLower.includes('beneficiary portal')) {
      key = 'check-eligibility-portal';
    } else if (titleLower.includes('biometric') || titleLower.includes('ekyc') || titleLower.includes('e-kyc')) {
      key = 'complete-biometric-ekyc';
    } else if (titleLower.includes('download') && (titleLower.includes('card') || titleLower.includes('ayushman'))) {
      key = 'download-ayushman-card';
    }

    const custom = key ? APPLICATION_STEP_DICTIONARY[key]?.[langCode] : null;

    return {
      ...step,
      title: custom?.title || translateGlossaryPhrase(step.title, langCode),
      description: custom?.description || translateGlossaryPhrase(step.description, langCode),
      tips: custom?.tips || (step.tips ? translateGlossaryPhrase(step.tips, langCode) : ''),
    };
  } catch {
    return step;
  }
};

