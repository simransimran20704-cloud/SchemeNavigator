export const translateSchemeContent = (scheme: Scheme, langCode: string = 'en-IN'): Scheme => {
  if (!scheme || langCode === 'en-IN' || langCode === 'en') return scheme;

  try {
    const sid = scheme.id || scheme.slug || '';
    const slug = scheme.slug || sid || '';
    const custom = SCHEME_TRANSLATIONS[sid]?.[langCode] || SCHEME_TRANSLATIONS[slug]?.[langCode] || {};

    const translatedDocs: DocumentRequirement[] = Array.isArray(scheme.documents)
      ? scheme.documents.map((d) => ({
          ...d,
          name: translateDocumentName(d.name, langCode),
          description: translateGlossaryPhrase(d.description, langCode),
        }))
      : [];

    const translatedBenefits: Benefit[] = Array.isArray(scheme.benefits)
      ? scheme.benefits.map((b) => translateBenefit(b, langCode))
      : [];

    const translatedSteps: ApplicationStep[] = Array.isArray(scheme.applicationSteps)
      ? scheme.applicationSteps.map((s) => translateApplicationStep(s, langCode))
      : [];

    const rawMinistry = scheme.verification?.ministryOrAuthority || '';
    const rawDept = scheme.verification?.sourceDepartment || '';

    const translatedMinistry = translateMinistry(rawMinistry, langCode);
    const translatedDept = translateMinistry(rawDept, langCode);

    const translatedName = custom.name || translateSchemeTitle(scheme.name, langCode);
    const translatedShortName = custom.shortName || custom.name || translateSchemeTitle(scheme.shortName || scheme.name, langCode);
    const translatedDesc = custom.shortDescription || custom.tagline || translateSchemeDescription(scheme, langCode);

    return {
      ...scheme,
      name: translatedName,
      shortName: translatedShortName,
      tagline: custom.tagline || translatedDesc,
      shortDescription: translatedDesc,
      detailedDescription: custom.detailedDescription || translatedDesc || scheme.detailedDescription,
      category: translateGlossaryPhrase(scheme.category || 'Welfare', langCode) as any,
      level: translateGlossaryPhrase(scheme.level || 'Central', langCode) as any,
      eligibility: scheme.eligibility ? {
        ...scheme.eligibility,
        customConditions: Array.isArray(scheme.eligibility.customConditions)
          ? scheme.eligibility.customConditions.map((c) => typeof c === 'string' ? translateGlossaryPhrase(c, langCode) : c)
          : scheme.eligibility.customConditions,
      } : scheme.eligibility,
      verification: scheme.verification ? {
        ...scheme.verification,
        ministryOrAuthority: translatedMinistry,
        sourceDepartment: translatedDept,
        lastUpdated: translateGlossaryPhrase(scheme.verification.lastUpdated, langCode),
      } : scheme.verification,
      documents: translatedDocs,
      benefits: translatedBenefits,
      applicationSteps: translatedSteps,
    };
  } catch (err) {
    console.warn('translateSchemeContent error:', err);
    return scheme;
  }
};
