/**
 * Translates any scheme title dynamically into the target Indic language.
 */
export const translateSchemeTitle = (title: string, langCode: string = 'en-IN'): string => {
  if (!title || langCode === 'en-IN' || langCode === 'en') return String(title || '');
  if (typeof title !== 'string') title = String(title || '');

  let text = title.trim();
  if (!text) return '';

  try {
    // 1. Direct glossary phrase check
    const direct = translateGlossaryPhrase(text, langCode);
    if (direct && direct !== text) return direct;

    // 2. Direct cache check (populated by Sarvam / Gemini)
    const cached = getCachedTranslation(text, langCode);
    if (cached) return cached;

    // 3. Exact / case-insensitive dictionary match in SCHEME_TITLE_LEXICON
    if (SCHEME_TITLE_LEXICON[text]?.[langCode]) {
      return SCHEME_TITLE_LEXICON[text][langCode];
    }
    const lowerText = text.toLowerCase();
    for (const [key, map] of Object.entries(SCHEME_TITLE_LEXICON)) {
      if (key.toLowerCase() === lowerText && map[langCode]) {
        return map[langCode];
      }
    }

    // 4. Multi-word phrase replacement (longest phrase matched first)
    const phrases = Object.keys(SCHEME_TITLE_LEXICON).sort((a, b) => b.length - a.length);
    for (const phrase of phrases) {
      const escaped = phrase.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&');
      const startBoundary = /^\w/.test(phrase) ? '\\b' : '';
      const endBoundary = /\w$/.test(phrase) ? '\\b' : '';
      const regex = new RegExp(`${startBoundary}${escaped}${endBoundary}`, 'gi');
      if (regex.test(text)) {
        const repl = SCHEME_TITLE_LEXICON[phrase]?.[langCode] || phrase;
        text = text.replace(regex, repl);
      }
    }

    // 5. If text still contains significant English letters, trigger Sarvam translation in background!
    if (typeof window !== 'undefined' && /[a-zA-Z]{3,}/.test(text)) {
      translateWithGemini(title.trim(), langCode).catch(() => {});
    }

    return text;
  } catch {
    return text;
  }
};

