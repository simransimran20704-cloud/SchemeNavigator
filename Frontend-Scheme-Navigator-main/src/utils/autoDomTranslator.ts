/**
 * Translates an arbitrary phrase into the target language using the dictionary
 */
export const translatePhrase = (text: string, targetLangCode: string): string => {
  if (!text || targetLangCode === 'en-IN' || targetLangCode === 'en') return text;
  const trimmed = text.trim();

  // 1. Direct glossary match
  if (PHRASE_GLOSSARY[trimmed] && PHRASE_GLOSSARY[trimmed][targetLangCode]) {
    return PHRASE_GLOSSARY[trimmed][targetLangCode];
  }

  // 2. Direct translation key match
  const dict = TRANSLATIONS[targetLangCode];
  if (dict) {
    const foundEntry = Object.entries(TRANSLATIONS['en-IN']).find(([, enVal]) => enVal === trimmed);
    if (foundEntry && dict[foundEntry[0]]) {
      return dict[foundEntry[0]];
    }
  }

  return text;
};
