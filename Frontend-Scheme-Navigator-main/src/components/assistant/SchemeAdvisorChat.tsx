// Helper to strip Markdown formatting for clean voice speech synthesis
const cleanTextForSpeech = (rawText: string): string => {
  return rawText
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/\*(.*?)\*/g, '$1')
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/^[-*•]\s+/gm, '')
    .replace(/^\d+\.\s+/gm, '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/https?:\/\/\S+/g, '')
    .replace(/[\n\r]+/g, '. ')
    .replace(/\s+/g, ' ')
    .trim();
};

// Helper to split long chat responses into natural, coherent speech chunks (300-450 characters)
const splitIntoChatSpeechChunks = (text: string): string[] => {
  if (!text) return [];
  const normalized = text.replace(/[\r\n]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (!normalized) return [];

  // Protect decimals (e.g. 1.5, 3.8) from splitting
  const protectedText = normalized.replace(/(\d)\.(\d)/g, '$1__DOT__$2');

  // Split by sentence delimiters: ., !, ?, or Indic danda (।)
  const rawSentences = protectedText.match(/[^.!?।\n]+[.!?।]+|[^.!?।\n]+$/g) || [protectedText];
  const chunks: string[] = [];
  let buffer = '';

  for (const raw of rawSentences) {
    const unmasked = raw.replace(/__DOT__/g, '.').trim();
    if (!unmasked) continue;

    if (buffer.length + unmasked.length + 1 <= 450) {
      buffer = buffer ? `${buffer} ${unmasked}` : unmasked;
    } else {
      if (buffer) {
        chunks.push(buffer.trim());
      }
      if (unmasked.length > 450) {
        const words = unmasked.split(' ');
        let temp = '';
        for (const w of words) {
          if ((temp + ' ' + w).trim().length > 400 && temp.length > 0) {
            chunks.push(temp.trim());
            temp = w;
          } else {
            temp = temp ? `${temp} ${w}` : w;
          }
        }
        buffer = temp;
      } else {
        buffer = unmasked;
      }
    }
  }

  if (buffer.trim()) {
    chunks.push(buffer.trim());
  }

  return chunks.length > 0 ? chunks : [normalized];
};

// Helper to render Markdown formatting nicely
const FormattedMessage: React.FC<{ text: string }> = ({ text }) => {
  const lines = text.split('\n');

  const formatInline = (str: string): React.ReactNode => {
    const parts = str.split(/(\*\*.*?\*\*|\*.*?\*)/g);
    return parts.map((part, idx) => {
      if (part.startsWith('**') && part.endsWith('**')) {
        return (
          <strong key={idx} className="font-bold text-inherit">
            {part.slice(2, -2)}
          </strong>
        );
      }
      if (part.startsWith('*') && part.endsWith('*')) {
        return (
          <em key={idx} className="italic opacity-90">
            {part.slice(1, -1)}
          </em>
        );
      }
      return part;
    });
  };

  return (
    <div className="space-y-2 text-xs sm:text-sm leading-relaxed">
      {lines.map((line, idx) => {
        const trimmed = line.trim();
        if (!trimmed) {
          return <div key={idx} className="h-1" />;
        }

        if (trimmed.startsWith('### ')) {
          return (
            <h4 key={idx} className="font-bold text-sm sm:text-base text-inherit mt-2 mb-1">
              {formatInline(trimmed.replace(/^###\s+/, ''))}
            </h4>
          );
        }

        if (trimmed.startsWith('## ')) {
          return (
            <h3 key={idx} className="font-extrabold text-base text-inherit mt-2.5 mb-1">
              {formatInline(trimmed.replace(/^##\s+/, ''))}
            </h3>
          );
        }

        if (/^[-*•]\s+/.test(trimmed)) {
          const content = trimmed.replace(/^[-*•]\s+/, '');
          return (
            <div key={idx} className="flex items-start gap-2 pl-1 py-0.5">
              <span className="text-teal-600 font-bold shrink-0 mt-0.5">•</span>
              <span className="flex-1">{formatInline(content)}</span>
            </div>
          );
        }

        const numMatch = trimmed.match(/^(\d+)\.\s+(.*)$/);
        if (numMatch) {
          return (
            <div key={idx} className="flex items-start gap-2 pl-1 py-0.5">
              <span className="text-teal-700 font-bold shrink-0 text-xs mt-0.5">{numMatch[1]}.</span>
              <span className="flex-1">{formatInline(numMatch[2])}</span>
            </div>
          );
        }

        return (
          <p key={idx} className="leading-relaxed">
            {formatInline(line)}
          </p>
        );
      })}
    </div>
  );
};

